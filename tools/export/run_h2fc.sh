#!/usr/bin/env bash
# PATCHES defaults to fd_h2_rbuf.h:h2fc-rbuf-nodata (the harness includes the
# copied fd_h2_rbuf.h first, so its include guard wins).
# Run one h2 / gRPC flow-control step configuration (h2fc_step.c): copy
# fd_h2_conn.c and fd_h2_tx.c, extract the gRPC flow-control callbacks
# verbatim from fd_grpc_client.c into grpc_fc_cb.c, apply an optional mutant
# to the copies, then clang -> SeaHorn front end -> sea-mlir export.
#   [MUT=file:name] [PATCHES=file:name] run_h2fc.sh OUTDIR [-DKEY=VAL ...]
# Same conventions as run_hpack.sh (mutants/NAME.sed, proofs/NAME.sed; each
# script must change its file).
set -euo pipefail
# harness sources: firedancer/harness/ in this repository (override with HERE)
HERE=${HERE:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../../firedancer/harness" && pwd)}
SEA=${SEA:?SEA=<seahorn install with the sea-mlir-export profile>}
FD=${FD:?FD=<firedancer checkout at 37c658197b29deada95ea95a1afb04f7baea28fa>}
H2="$FD/src/waltz/h2"
GRPC="$FD/src/waltz/grpc/fd_grpc_client.c"
OUT=$(realpath -m "$1"); shift
mkdir -p "$OUT"
DEFS=("$@")
FILES=(fd_h2_conn.c fd_h2_tx.c fd_h2_rbuf.h)
for f in "${FILES[@]}"; do cp "$H2/$f" "$OUT/$f"; done
# verbatim extraction: the return-type line, then the function to its '}'
extract() {
  awk -v n="$1" '
    $0 ~ ("^" n "\\(") { print prev; f = 1 }
    f { print } f && /^}/ { exit }
    { prev = $0 }' "$GRPC"
}
{
  echo "/* generated by run_h2fc.sh from fd_grpc_client.c (verbatim) */"
  for fn in fd_grpc_h2_stream_reset fd_grpc_client_send_stream_quota \
            fd_grpc_h2_window_update fd_grpc_h2_stream_window_update \
            fd_grpc_h2_initial_window_update; do
    body=$(extract "$fn"); [[ -n "$body" ]] || { echo "extract $fn failed" >&2; exit 2; }
    printf '%s\n\n' "$body"
  done
} > "$OUT/grpc_fc_cb.c"
FILES+=(grpc_fc_cb.c)
cp "$OUT/grpc_fc_cb.c" "$OUT/grpc_fc_cb.c.orig"
apply() {  # FILE SCRIPT
  local f="$OUT/$1" s="$2"
  [[ -f "$f" ]] || { echo "unknown file $1" >&2; exit 2; }
  cp "$f" "$OUT/before.tmp"
  sed -i -f "$s" "$f"
  if cmp -s "$OUT/before.tmp" "$f"; then echo "$s did not apply to $1" >&2; exit 2; fi
  rm -f "$OUT/before.tmp"
}
for p in ${PATCHES-fd_h2_rbuf.h:h2fc-rbuf-nodata}; do apply "${p%%:*}" "$HERE/proofs/${p#*:}.sed"; done
for m in ${MUT:-}; do apply "${m%%:*}" "$HERE/mutants/${m#*:}.sed"; done
: > "$OUT/applied.diff"
for f in fd_h2_conn.c fd_h2_tx.c fd_h2_rbuf.h; do diff "$H2/$f" "$OUT/$f" >> "$OUT/applied.diff" || true; done
diff "$OUT/grpc_fc_cb.c.orig" "$OUT/grpc_fc_cb.c" >> "$OUT/applied.diff" || true
clang-18 -c -emit-llvm -D__SEAHORN__ -fdeclspec -O1 -Xclang -disable-llvm-optzns \
  -fgnu89-inline -m64 -g -std=c17 -DFD_DCHECK_STYLE=1 -DFD_H2_HAS_SOCKETS=0 \
  -I"$OUT" -I"$SEA/include" -I"$FD/src" -I"$H2" -I"$FD/src/waltz/grpc" -I"$HERE" "${DEFS[@]}" \
  -o "$OUT/harness.bc" "$HERE/${SRC:-h2fc_step.c}"
rm -f "$OUT/prog.mlir" "$OUT/sea.log"
# bench export: SeaHorn sea-mlir-export profile (docs/sea-mlir-export.md)
"$SEA/bin/sea" yama -y sea-mlir-export -y "$HERE/sea.yaml" --bound="${BOUND:-8}" \
  --horn-sea-mlir-out="$OUT/prog.mlir" ${SEA_EXTRA:-} "$OUT/harness.bc" > "$OUT/sea.log" 2>&1 \
  || { echo "export failed, see $OUT/sea.log" >&2; exit 1; }
[[ -s "$OUT/prog.mlir" ]] || { echo "export failed, see $OUT/sea.log" >&2; exit 1; }
